"""Bake approved phase-one art; originals are never modified. Run column exporter first."""
from pathlib import Path
from PIL import Image
import json,hashlib
ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'monsters/stage-02/boss-siblings-lineup-20261103'
OUT=BASE/'unity-phase1';OUT.mkdir(exist_ok=True)
def read(n):return Image.open(BASE/n).convert('RGBA')
def trim(im):return im.crop(im.getchannel('A').point(lambda a:255 if a>128 else 0).getbbox())
def save(im,n):im.save(OUT/(n+'.png'))
board=read('map-preview/assets/bosses-subtle-v4-transparent.png')
for name,l,r in [('blue-standing',0,.29),('rose-standing',.29,.65)]:
 im=trim(board.crop((int(board.width*l),0,int(board.width*r),board.height)))
 save(im.resize((round(im.width*102.4/im.height),102),Image.Resampling.NEAREST),name)
im=trim(read('rose-static-shot/rose-hover-firing-original.png'))
save(im.resize((round(im.width*139.2/im.height),139),Image.Resampling.NEAREST),'rose-shot')
im=trim(read('rose-static-shot/rose-enchanted-bolt-original.png'))
save(im.resize((96,32),Image.Resampling.LANCZOS),'rose-bolt')
save(read('phase1-device-concepts/front-machine-v3/device-pixel-80.png'),'machine')
save(read('phase1-playtest/effects/ink-root/root.png'),'root')
save(read('map-preview/assets/terrain-preview.png').crop((128,192,224,208)),'tile')
def atlas(frames,cols,name):
 w,h=frames[0].size;a=Image.new('RGBA',(w*cols,h*((len(frames)+cols-1)//cols)))
 for i,im in enumerate(frames):a.paste(im,((i%cols)*w,(i//cols)*h))
 save(a,name)
motion=json.loads((BASE/'blue-palm-return/motion.json').read_text(encoding='utf-8'))
atlas([read(f'blue-palm-return/frames/{i:02}.png') for i in motion['keys']],4,'blue-palm')
atlas([read(f'blue-palm-return/slow-orb-v2/{i:02}.png') for i in range(4)],4,'blue-orb')
atlas([read(f'phase1-playtest/effects/ink-root/trap-{i:02}.png') for i in range(8)],4,'trap')
raw=(OUT/'ink-column.rgba').read_bytes();stride=240*220*4
atlas([Image.frombytes('RGBA',(240,220),raw[i*stride:(i+1)*stride]) for i in range(132)],12,'ink-column')
(OUT/'ink-column.rgba').unlink() # intermediate generated by the exporter, never an original
config={'format':'deviant-phase1-art-v1','inkWidthPx':42,'inkHeightPx':129,'inkGroundY':180,'inkFrameRate':60,'inkFrames':132,'blueKeys':motion['keys'],'blueDurationsMs':motion['durationsMs'],'blueReleaseIndex':7,'pixelsPerUnit':32,'note':'Visuals only; combat timing and collider geometry remain in chapter2_rose_blue.json.'}
(OUT/'binding.json').write_text(json.dumps(config,indent=2)+'\n')
for rel in ['phase1-playtest/effects/ink-burst/water-column-spec/game-column.mjs','phase1-playtest/game.mjs','phase1-playtest/index.html']:
 p=BASE/rel;s=p.read_text(encoding='utf-8');s=s.replace('height=102,width=30','height=129,width=42').replace('width:30,height:102','width:42,height:129').replace('value="30"','value="42"').replace('value="102"','value="129"');p.write_text(s,encoding='utf-8')
# Refresh package indexes after approved preview and derivative changes.
catalog=json.loads((ROOT/'catalog.json').read_text(encoding='utf-8'));manifest=json.loads((ROOT/'generated-assets.json').read_text(encoding='utf-8'));records={v['path']:v for v in manifest['files']}
for group in ['monsters/stage-02/boss-siblings-lineup-20261103']:
 folder=ROOT/group;asset=json.loads((folder/'asset.json').read_text(encoding='utf-8'));asset['files']=sorted(p.relative_to(folder).as_posix() for p in folder.rglob('*') if p.is_file() and p.name!='asset.json')
 if folder==BASE:asset['motionReview']['phase1Playtest']='user-approved';asset['gameIntegration']='phase1-unity-in-progress'
 (folder/'asset.json').write_text(json.dumps(asset,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
 for entry in catalog['assets']:
  if entry['path']==group:entry['fileCount']=len(asset['files'])
 for p in [folder/'asset.json',*[folder/n for n in asset['files']]]:
  name=p.relative_to(ROOT).as_posix();b=p.read_bytes();records[name]={'path':name,'bytes':len(b),'sha256':hashlib.sha256(b).hexdigest()}
manifest['files']=sorted(records.values(),key=lambda x:x['path']);(ROOT/'generated-assets.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8');(ROOT/'catalog.json').write_text(json.dumps(catalog,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('Approved phase1 derivative atlases built and indexed')
