"""Generate the engine-independent tuning used by Unity and the regression harness."""
import argparse
import json
import math
import re
from pathlib import Path

root = Path(__file__).resolve().parents[2]
source = root / 'data/combat/chapter2_rose_blue.json'
data = json.loads(source.read_text(encoding='utf-8'))
if data.get('schema') != 1 or not isinstance(data.get('values'), dict):
    raise SystemExit('Unsupported Rose/Blue schema')
lines = ['// Generated by tools/combat/export_chapter2_rose_blue.py; edit data/combat/chapter2_rose_blue.json.',
         'namespace Deviant.Chapter2.RoseBlue', '{', '    public static class Tuning', '    {']
for key, value in data['values'].items():
    if not re.fullmatch('[A-Z][A-Za-z0-9]*', key) or type(value) not in (int, float) or not math.isfinite(value) or value < 0 or (value == 0 and key != 'Phase1Rest'):
        raise SystemExit(f'Invalid tuning: {key}')
    lines.append(f'        public const double {key} = {value};')
if data['values']['BounceExplodeAt'] <= data['values']['BounceWhiteAt']:
    raise SystemExit('Explosion must follow whitening')
values = data['values']
for key in ['PlatformCount', 'TrapCount', 'BounceCount', 'Phase1ArrowCount', 'DuoShotCount', 'RainCount',
            'Phase1ArrowMinDamage', 'Phase1ArrowMaxDamage']:
    if int(values[key]) != values[key]:
        raise SystemExit(f'{key} must be an integer')
if values['PlatformCount'] != 7 or values['TrapCount'] != 7:
    raise SystemExit('The approved 2/3/2 arena requires 7 platforms / 7 pulse traps')
if values['RainCount'] < 2 or values['Phase1ArrowMaxDamage'] < values['Phase1ArrowMinDamage']:
    raise SystemExit('Invalid rain count or arrow damage range')
if values['BounceCount'] * values['BounceTell'] >= values['BounceWhiteAt']:
    raise SystemExit('All bounce arrows must spawn before whitening')
if not 0 < values['BounceRandomMinDegrees'] <= values['BounceRandomMaxDegrees'] < 90:
    raise SystemExit('Normal reflections must point inward')
for key, value in data.get('policies', {}).items():
    if not re.fullmatch('[A-Z][A-Za-z0-9]*', key) or type(value) is not bool:
        raise SystemExit(f'Invalid boolean policy: {key}')
    lines.append(f'        public const bool {key} = {str(value).lower()};')
lines += ['    }', '    // Replaceable prototype presentation; not final cutscene timing.', '    public static class TemporaryPresentation', '    {']
for key, value in data.get('temporaryPresentation', {}).items():
    if not re.fullmatch('[A-Z][A-Za-z0-9]*', key) or type(value) not in (int, float) or not math.isfinite(value) or value <= 0:
        raise SystemExit(f'Invalid temporary presentation: {key}')
    lines.append(f'        public const double {key} = {value};')
lines += ['    }', '}', '']
out = root / 'unity/Assets/Chapter2/RoseBlue/Tuning.g.cs'
expected = '\n'.join(lines)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if not out.exists() or out.read_text(encoding='utf-8') != expected:
        raise SystemExit('Rose/Blue tuning is out of date')
else:
    out.write_text(expected, encoding='utf-8')
print('Rose/Blue tuning synchronized')
