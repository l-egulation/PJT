"""Render the audio timing reference from authored numeric sources, without editing them."""
import argparse
import json
from pathlib import Path

from melee_source import load_melee

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'data/combat'
OUTPUT = ROOT / 'docs/development/presentation/audio/basic-attack-audio-timing.md'


def read(name):
    return json.loads((DATA / name).read_text(encoding='utf-8-sig'))


def ms(seconds):
    return f'{seconds * 1000:.1f}'.rstrip('0').rstrip('.')


def melee_table(forms, trials=None):
    lines = [
        '| 무기·타 | 타 시작(연계) | 판정 시작(타 내부) | 판정 시작(연계) | 판정 지속 | 타 전체 길이 | 판정 종료 후 회복 |',
        '|---|---:|---:|---:|---:|---:|---:|',
    ]
    for form in forms:
        basic = form['basic']
        trial = (trials or {}).get(form['id'], {})
        speed, extra = trial.get('scale', 1), trial.get('lastHitExtraRecoverySeconds', 0)
        start = 0
        for i, (duration, impact, active) in enumerate(zip(
                basic['motion_durations'], basic['local_hit_times'], basic['active_durations'])):
            duration = duration / speed + (extra if i == len(basic['damages']) - 1 else 0)
            impact, active = impact / speed, active / speed
            values = [start, impact, start + impact, active, duration, duration - impact - active]
            lines.append(f"| {form['name']} {i + 1}타 | " + ' | '.join(map(ms, values)) + ' |')
            start += duration
    return '\n'.join(lines)


